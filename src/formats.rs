pub const FOLDER: &str = "folder";

pub fn by_id(id: &str) -> Option<&'static Format> {
    KNOWN.iter().find(|f| f.id.eq_ignore_ascii_case(id))
}

/// The extension a path is known by, compound ones first ("tar.gz", "kepub.epub").
pub fn extension_of(path: &std::path::Path) -> String {
    let name = path
        .file_name()
        .map(|n| n.to_string_lossy().to_lowercase())
        .unwrap_or_default();
    let compound = KNOWN
        .iter()
        .flat_map(|f| f.extensions)
        .filter(|e| e.contains('.') && name.len() > e.len() + 1 && name.ends_with(&format!(".{e}")))
        .max_by_key(|e| e.len());
    match compound {
        Some(e) => e.to_string(),
        None => name
            .rsplit_once('.')
            .map(|(_, e)| e.to_string())
            .unwrap_or_default(),
    }
}

pub fn detect(path: &std::path::Path) -> Option<&'static Format> {
    if path.is_dir() {
        return by_id(FOLDER);
    }
    let ext = extension_of(path);
    KNOWN.iter().find(|f| f.extensions.contains(&ext.as_str()))
}

/// The file name without its known extension.
pub fn stem_of(path: &std::path::Path) -> String {
    let name = path
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_default();
    let ext = extension_of(path);
    if ext.is_empty() || path.is_dir() {
        name
    } else {
        name[..name.len() - ext.len() - 1].to_string()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::Path;

    #[test]
    fn detects_compound_and_plain_extensions() {
        assert_eq!(detect(Path::new("a/b.tar.gz")).unwrap().id, "tgz");
        assert_eq!(detect(Path::new("x.JPEG")).unwrap().id, "jpg");
        assert_eq!(detect(Path::new("book.kepub.epub")).unwrap().id, "kepub");
        assert_eq!(stem_of(Path::new("a/b.tar.gz")), "b");
        assert!(detect(Path::new("noext")).is_none());
        assert_eq!(KNOWN.len(), 246);
    }
}
